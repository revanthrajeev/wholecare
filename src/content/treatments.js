export function treatmentBySlug(slug) {
  return TREATMENTS.find((t) => t.slug === slug) || null;
}

function mid([lo, hi]) {
  return (lo + hi) / 2;
}

// Cheapest destination by range midpoint, plus a conservative "typical saving"
// vs. US list prices, rounded down to the nearest 5%.
export function priceSummary(t) {
  const entries = Object.entries(t.prices || {});
  if (!entries.length) return null;
  const [cheapestCountry, cheapestRange] = entries.reduce((a, b) => (mid(b[1]) < mid(a[1]) ? b : a));
  const fromUSD = Math.min(...entries.map(([, r]) => r[0]));
  const us = t.home?.["United States"];
  const savingPct = us ? Math.floor(((1 - mid(cheapestRange) / mid(us)) * 100) / 5) * 5 : null;
  return { cheapestCountry, cheapestRange, fromUSD, savingPct, usRange: us || null };
}
